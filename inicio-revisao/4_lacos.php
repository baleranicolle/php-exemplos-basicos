<?php

// Laço (FOR) para tabuada 8 
for ($i = 1; $i <=10; $i++) {
    echo "8 x $i = " . (8 * $i) . "\n";
}

// While -(Enquanto) Contagem regressiva
echo "</n>";
$i = 5; "/n";
while ($i >0) {
    echo $i. "</n>";
    $i--;
}

// Do While - (Faça enquanto) Executa ao menos 1 vez
echo "</n>";
$x = 10;
do {
    echo "x vale: $x </n>";
    $x++;
} while ($x < 10);